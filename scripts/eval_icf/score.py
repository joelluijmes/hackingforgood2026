"""Score a generated ICF docx against the approved ICF of a case.

uv run --project backend python scripts/eval_icf/score.py <case> <generated.docx> [--out metrics.json]

Metrics (judge prompts below are FIXED across experiments):
  recall            weighted share of the approved ICF's trial-specific facts present in the draft
  recall_avail      same, restricted to facts the sponsor documents contain (what a good generator can reach)
  wrong             facts the draft contradicts
  halluc_major/minor  unsupported trial-specific claims / invented site-specific values (per judge)
  gaps              number of [[GAP]] flags in the draft; gaps_avail = facts that were available in sponsor
                    docs but absent (missing info the draft should have filled)
  purple            share of mandatory (purple) template paragraphs kept (>=0.9 similarity)
  headings / order  approved headings found in the draft / in the right order
  num_recall / num_prec   exactness of numbers (trial-specific numbers found; draft numbers grounded)
  residue           leftover [[BLUE]] placeholders + [bracketed template text] in the draft
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from concurrent.futures import ThreadPoolExecutor

from common import (
    CASES,
    WORK,
    bucket,
    doc_blocks,
    judge_json,
    norm,
    segments,
    sponsor_text,
)

SPONSOR_CAP = 200_000

GOLD_SYS = (
    "You are a meticulous evaluator of clinical-trial informed consent forms (ICFs). "
    "Answer in strict JSON."
)
GOLD_PROMPT = """Below are (1) one SECTION of the final, approved Belgian ICF for a clinical trial and (2) the SPONSOR DOCUMENTS the ICF was derived from.

Extract a checklist of the TRIAL-SPECIFIC facts stated in the approved section: disease/condition, treatment/IMP names, design, randomisation, numbers (participants, doses, durations, visits, ages, periods), procedures, trial-specific risks/side effects, trial-specific benefits/alternatives, sample/data specifics, contraception rules, etc.
Do NOT include: generic consent boilerplate that any Belgian ICF contains (voluntary participation text, GDPR rights lists, ombudsperson wording, standard definitions), site-specific blanks (site name, phone numbers, e-mail addresses, insurer name/policy no., investigator names), or purely formatting content.
Each fact must be atomic, self-contained and short (one sentence, keep exact numbers/names). At most 25 facts; fewer if the section has few trial-specific facts (return an empty list for pure boilerplate).
For each fact say whether the SPONSOR DOCUMENTS contain that information (true/false/"partly" - partly = related info but not the exact detail).

Return JSON: {{"facts": [{{"fact": str, "in_sponsor": true|false|"partly"}}]}}

=== APPROVED ICF SECTION: {title} ===
{section}

=== SPONSOR DOCUMENTS ===
{sponsor}
"""

ASSESS_SYS = GOLD_SYS
ASSESS_PROMPT = """You are given a DRAFT informed consent form generated by a tool, and a numbered checklist of facts that the approved final ICF contains.
In the DRAFT, "[[GAP: text]]" marks a place where the tool explicitly flagged that information is missing and must be added by a human; "[[BLUE: text]]" marks an unfilled template placeholder.
For each checklist fact decide where it stands in the DRAFT (search the whole draft, the fact may be in another section):
- "present": the draft states the same fact (same meaning, same numbers/names). Wording may differ.
- "partial": the draft contains part of it, is vaguer, or misses a number/detail.
- "wrong": the draft states something that contradicts the fact (e.g. other number, other drug).
- "absent": not in the draft (whether or not a gap flag exists).
Also set "gap_flagged": true if the draft has a [[GAP]] / [[BLUE]] flag at the place where this fact belongs.

Return JSON: {{"results": [{{"i": int, "status": "present|partial|wrong|absent", "gap_flagged": bool}}]}} with one entry per fact.

=== CHECKLIST ===
{facts}

=== DRAFT ===
{draft}
"""

HALL_SYS = GOLD_SYS
HALL_PROMPT = """You audit one SECTION of a DRAFT informed consent form for a clinical trial, produced by an automatic tool. The tool was only allowed to use facts from the SPONSOR DOCUMENTS (and the Belgian national ICF template, whose generic boilerplate wording is acceptable).
List every claim in the section that is a problem:
- "invented_fact": a trial-specific fact (drug, dose, number, duration, procedure, risk, eligibility, endpoint, date, name) that is NOT supported by the SPONSOR DOCUMENTS and is not generic ICF boilerplate. A claim contained in the REFERENCE APPROVED ICF but absent from the sponsor documents still counts as unsupported if it is trial-specific.
- "wrong": contradicts the sponsor documents or the reference approved ICF.
- "site_specific_invented": a concrete site-specific value (site/hospital name or address, phone number, e-mail, insurer name, policy number, investigator name, vendor) that is not present in the SPONSOR DOCUMENTS. Placeholders such as "[Phone N]" or "[[GAP: ...]]" are correct and must NOT be listed. Well-known public authority contacts that are mandatory template text (Belgian DPA, CT College, FAMHP, euclinicaltrials.eu) are fine.
- "garbled": text that is nonsensical, contradictory with a neighbouring sentence, left-over template instruction/guidance (e.g. "[Choose ...]", "[If applicable ...]"), or placed in a section where it does not belong.
Severity: "major" = would mislead a participant or reviewer, "minor" = small.
Do not list stylistic issues. Do not list gaps ([[GAP]]) as problems.

Return JSON: {{"issues": [{{"type": "...", "severity": "major|minor", "quote": "short quote", "why": "short reason"}}]}}

=== DRAFT SECTION: {title} ===
{section}

=== SPONSOR DOCUMENTS ===
{sponsor}

=== REFERENCE APPROVED ICF (for judging wrong/contradiction only) ===
{approved}
"""


def _gold(case_name: str, seg: dict, sponsor: str) -> list[dict]:
    d = judge_json(
        GOLD_PROMPT.format(title=seg["title"], section=seg["text"], sponsor=sponsor[:SPONSOR_CAP]),
        GOLD_SYS,
    )
    return [f for f in d.get("facts", []) if isinstance(f, dict) and f.get("fact")]


def _nums(s: str) -> set[str]:
    out = set()
    for m in re.finditer(r"\d+(?:[.,]\d+)?", s):
        out.add(m.group(0).replace(",", "."))
    return out


def _bestratio(a: str, cands: list[str]) -> float:
    best = 0.0
    la = len(a)
    for c in cands:
        if not c or abs(len(c) - la) > max(la, len(c)) * 0.6:
            continue
        sm = difflib.SequenceMatcher(None, a, c, autojunk=False)
        if sm.real_quick_ratio() < best or sm.quick_ratio() < best:
            continue
        best = max(best, sm.ratio())
        if best > 0.98:
            break
    return best


def score(case_name: str, gen_path: str, verbose: bool = False) -> dict:
    case = CASES[case_name]
    b = bucket()
    sponsor = sponsor_text(case)
    appr_blocks = doc_blocks(str(b / case["approved"]), mark=False)
    gen_blocks = doc_blocks(gen_path)
    tpl_blocks = doc_blocks(str(b / case["template"]), mark=False)
    approved_txt = "\n".join(x["text"] for x in appr_blocks)
    gen_txt_marked = "\n".join(x["marked"] for x in gen_blocks)
    gen_txt = "\n".join(x["text"] for x in gen_blocks)
    tpl_txt = "\n".join(x["text"] for x in tpl_blocks)
    m: dict = {"case": case_name, "gen_words": len(gen_txt.split())}

    # --- LLM judged: gold facts recall ---
    aseg = segments(appr_blocks)
    with ThreadPoolExecutor(6) as ex:
        golds = list(ex.map(lambda s: _gold(case_name, s, sponsor), aseg))
    all_facts = []
    for s, gl in zip(aseg, golds, strict=True):
        for f in gl:
            all_facts.append({"section": s["title"], **f})
    # assess in batches of 25 facts against the full draft
    batches = [all_facts[i : i + 25] for i in range(0, len(all_facts), 25)]

    def _assess(batch):
        facts = "\n".join(f"{i}. {f['fact']}" for i, f in enumerate(batch))
        d = judge_json(ASSESS_PROMPT.format(facts=facts, draft=gen_txt_marked[:SPONSOR_CAP]), ASSESS_SYS)
        res = {r["i"]: r for r in d.get("results", []) if isinstance(r, dict) and "i" in r}
        return [res.get(i, {"status": "absent", "gap_flagged": False}) for i in range(len(batch))]

    with ThreadPoolExecutor(6) as ex:
        assessed = [r for rs in ex.map(_assess, batches) for r in rs]
    w = {"present": 1.0, "partial": 0.5, "wrong": 0.0, "absent": 0.0}
    for f, r in zip(all_facts, assessed, strict=True):
        f["status"] = r.get("status", "absent")
        f["gap_flagged"] = bool(r.get("gap_flagged"))
    n = len(all_facts) or 1
    avail = [f for f in all_facts if f.get("in_sponsor") in (True, "partly")]
    m["facts"] = len(all_facts)
    m["facts_avail"] = len(avail)
    m["recall"] = round(sum(w.get(f["status"], 0) for f in all_facts) / n, 3)
    m["recall_avail"] = round(sum(w.get(f["status"], 0) for f in avail) / (len(avail) or 1), 3)
    m["wrong"] = sum(1 for f in all_facts if f["status"] == "wrong")
    m["absent_avail"] = sum(1 for f in avail if f["status"] == "absent")
    m["gaps_avail"] = sum(1 for f in avail if f["status"] == "absent" and f["gap_flagged"])
    m["gaps"] = len(re.findall(r"\[\[GAP:", gen_txt_marked))

    # --- LLM judged: hallucinations per generated section ---
    gseg = segments(gen_blocks, min_words=150)

    def _hall(seg):
        d = judge_json(
            HALL_PROMPT.format(
                title=seg["title"],
                section=seg["text"],
                sponsor=sponsor[:SPONSOR_CAP],
                approved=approved_txt[:SPONSOR_CAP],
            ),
            HALL_SYS,
        )
        return [{"section": seg["title"], **i} for i in d.get("issues", []) if isinstance(i, dict)]

    with ThreadPoolExecutor(6) as ex:
        issues = [i for xs in ex.map(_hall, gseg) for i in xs]
    m["halluc_major"] = sum(
        1 for i in issues if i.get("severity") == "major" and i.get("type") != "garbled"
    )
    m["halluc_minor"] = sum(
        1 for i in issues if i.get("severity") != "major" and i.get("type") != "garbled"
    )
    m["site_invented"] = sum(1 for i in issues if i.get("type") == "site_specific_invented")
    m["garbled"] = sum(1 for i in issues if i.get("type") == "garbled")

    # --- deterministic: purple retention ---
    gen_norm = [norm(x["text"]) for x in gen_blocks]
    purple = [norm(x["text"]) for x in tpl_blocks if x["purple"] and len(x["text"].split()) >= 6]
    kept = sum(1 for p in purple if _bestratio(p, gen_norm) >= 0.9)
    m["purple_total"] = len(purple)
    m["purple"] = round(kept / (len(purple) or 1), 3)

    # --- deterministic: headings ---
    def heads(blocks):
        return [
            norm(x["text"])
            for x in blocks
            if x["heading"] or x["style"].lower().startswith("subtitle")
        ]

    ah, gh = heads(appr_blocks), heads(gen_blocks)
    pos, found, last = [], 0, -1
    lcs_hits = 0
    for h in ah:
        best, bi = 0.0, -1
        for i, g in enumerate(gh):
            r = difflib.SequenceMatcher(None, h, g).ratio()
            if r > best:
                best, bi = r, i
        if best >= 0.8:
            found += 1
            pos.append(bi)
    for p in pos:
        if p > last:
            lcs_hits += 1
            last = p
    m["headings"] = round(found / (len(ah) or 1), 3)
    m["order"] = round(lcs_hits / (len(ah) or 1), 3)

    # --- deterministic: numbers ---
    a_n, s_n, t_n, g_n = _nums(approved_txt), _nums(sponsor), _nums(tpl_txt), _nums(gen_txt)
    target = {x for x in a_n if x in s_n and x not in t_n and len(x) >= 2}
    m["num_recall"] = round(len(target & g_n) / (len(target) or 1), 3)
    grounded = s_n | t_n | a_n
    ungrounded = sorted(x for x in g_n if x not in grounded)
    m["num_prec"] = round(1 - len(ungrounded) / (len(g_n) or 1), 3)
    m["ungrounded_numbers"] = ungrounded[:30]

    # --- residue ---
    m["residue_blue"] = len(re.findall(r"\[\[BLUE:", gen_txt_marked))
    clean = re.sub(r"\[\[(?:GAP|BLUE):[^\]]*\]\]", "", gen_txt_marked)
    m["residue_brackets"] = len(re.findall(r"\[[^\]\n]{4,}\]", clean))

    m["_facts"] = all_facts
    m["_issues"] = issues
    return m


SUMMARY_KEYS = [
    "gen_words", "facts", "recall", "recall_avail", "wrong", "absent_avail", "gaps",
    "halluc_major", "halluc_minor", "site_invented", "garbled", "purple", "headings", "order",
    "num_recall", "num_prec", "residue_blue", "residue_brackets",
]  # fmt: skip


def summary(m: dict) -> str:
    return " | ".join(f"{k}={m[k]}" for k in SUMMARY_KEYS if k in m)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("case", choices=list(CASES))
    ap.add_argument("docx")
    ap.add_argument("--out")
    a = ap.parse_args()
    res = score(a.case, a.docx)
    out = a.out or a.docx.replace(".docx", ".metrics.json")
    with open(out, "w") as fh:
        json.dump(res, fh, indent=1, ensure_ascii=False)
    print(summary(res))
    sys.exit(0)
